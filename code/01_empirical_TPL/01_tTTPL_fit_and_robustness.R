read_otu_matrix <- function(file) {
  x <- read.csv(
    file,
    header = TRUE,
    row.names = 1,
    check.names = FALSE
  )
  
  x[] <- lapply(x, as.numeric)
  mat <- as.matrix(x)
  storage.mode(mat) <- "double"
  
  # Remove taxa that are zero across all available years.
  keep <- rowSums(mat, na.rm = TRUE) > 0
  mat <- mat[keep, , drop = FALSE]
  
  if (anyNA(mat)) {
    stop("NA values detected in OTU table: ", file)
  }
  
  if (any(mat < 0)) {
    stop("Negative abundance values detected in OTU table: ", file)
  }
  
  mat
}


align_plot_to_metadata <- function(mat, plot_id, env) {
  
  common_samples <- intersect(colnames(mat), env$Sample_name)
  
  # For a true plot-level file, every matched annual sample should map
  # to exactly one metadata plot. This check catches mislabeled files.
  matched_plots <- unique(
    env$plot[match(common_samples, env$Sample_name)]
  )
  matched_plots <- matched_plots[!is.na(matched_plots)]
  
  if (length(common_samples) < MIN_YEARS) {
    stop(
      plot_id, ": only ", length(common_samples),
      " sample names match the environmental table."
    )
  }
  
  meta <- env[match(common_samples, env$Sample_name), , drop = FALSE]
  
  # Verify that all matched samples really belong to this plot.
  if (length(matched_plots) != 1 || matched_plots[1] != plot_id) {
    stop(
      "File expected for plot ", plot_id,
      " contains sample columns mapping to metadata plot(s): ",
      paste(matched_plots, collapse = ", "),
      ". Please inspect file: ",
      basename(deparse(substitute(mat)))
    )
  }
  
  wrong_plot <- unique(meta$plot[meta$plot != plot_id])
  if (length(wrong_plot) > 0) {
    stop(
      plot_id,
      ": sample-name matching points to another plot: ",
      paste(wrong_plot, collapse = ", ")
    )
  }
  
  ord <- order(meta$year)
  meta <- meta[ord, , drop = FALSE]
  
  # Reorder abundance matrix to 2010 -> 2020.
  mat <- mat[, meta$Sample_name, drop = FALSE]
  
  list(mat = mat, meta = meta)
}


