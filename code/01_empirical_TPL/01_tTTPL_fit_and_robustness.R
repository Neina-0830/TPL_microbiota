# -----------------------------
# 9. SPLIT-PLOT MIXED MODELS
# -----------------------------
#
# Experimental structure:
# - warming and precipitation operate at the whole-plot level
# - clipping is the paired subplot factor (N/S)
# - Number identifies the 24 whole plots
#
# Model:
# metric ~ Warm * Precipitation * Clipping
#          + (1 | block) + (1 | WholePlotID)
#
# Equivalent nesting logic:
# whole plots are nested within blocks, with two clipping subplots
# within each whole plot.
# -------------------------------------------------------------

write_lmer_outputs <- function(model, prefix) {
  
  # Fixed effects.
  co <- as.data.frame(summary(model)$coefficients)
  co$Term <- rownames(co)
  rownames(co) <- NULL
  co <- co[, c("Term", setdiff(colnames(co), "Term"))]
  
  write.csv(
    co,
    paste0(prefix, "_coefficients.csv"),
    row.names = FALSE,
    quote = FALSE
  )
  
  # Type-III ANOVA from lmerTest.
  an <- as.data.frame(anova(model, type = 3))
  an$Term <- rownames(an)
  rownames(an) <- NULL
  an <- an[, c("Term", setdiff(colnames(an), "Term"))]
  
  write.csv(
    an,
    paste0(prefix, "_anova_type3.csv"),
    row.names = FALSE,
    quote = FALSE
  )
  
  capture.output(
    summary(model),
    file = paste0(prefix, "_summary.txt")
  )
}


