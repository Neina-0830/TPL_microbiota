prepare_sensitivity_model_data <- function(d) {
  
  d <- d[is.finite(d$Beta_sensitivity), , drop = FALSE]
  
  d$Warming <- as.numeric(d$warm)
  d$Clipping <- as.numeric(d$clip)
  
  d$Precipitation <- ifelse(
    d$precip == 0.5,
    -0.5,
    ifelse(
      d$precip == 1,
      0,
      ifelse(d$precip == 2, 1, NA_real_)
    )
  )
  
  d$Block <- factor(d$block)
  d$WholePlotID <- factor(d$WholePlotID)
  d$BlockWholePlotID <- interaction(
    d$Block,
    d$WholePlotID,
    drop = TRUE,
    sep = ":"
  )
  
  d
}


summarize_one_emm_contrast <- function(cc) {
  
  ss <- as.data.frame(
    summary(
      cc,
      infer = c(TRUE, TRUE),
      adjust = "none"
    )
  )
  
  data.frame(
    Estimate = ss$estimate[1],
    SE = ss$SE[1],
    df = ss$df[1],
    CI_low = ss$lower.CL[1],
    CI_high = ss$upper.CL[1],
    t_ratio = ss$t.ratio[1],
    P = ss$p.value[1],
    stringsAsFactors = FALSE
  )
}


# Extract six warming contrasts plus their equal-weight average from the final
# numeric precipitation model used in the Reviewer-2 downstream analysis.
extract_sensitivity_warming_contrasts <- function(model) {
  
  emm <- emmeans::emmeans(
    model,
    specs = ~ Warming * Precipitation * Clipping,
    at = list(
      Warming = c(0, 1),
      Precipitation = c(-0.5, 0, 1),
      Clipping = c(0, 1)
    ),
    lmer.df = "satterthwaite"
  )
  
  grid <- as.data.frame(emm)
  
  combos <- expand.grid(
    Precipitation = c(-0.5, 0, 1),
    Clipping = c(0, 1),
    KEEP.OUT.ATTRS = FALSE,
    stringsAsFactors = FALSE
  )
  
  context_rows <- vector("list", nrow(combos))
  overall_weight <- rep(0, nrow(grid))
  
  precip_label <- function(p) {
    if (p == -0.5) return("Half")
    if (p == 0) return("Ambient")
    if (p == 1) return("Double")
    as.character(p)
  }
  
  for (j in seq_len(nrow(combos))) {
    
    p <- combos$Precipitation[j]
    c0 <- combos$Clipping[j]
    
    iw <- which(
      abs(grid$Warming - 1) < 1e-12 &
        abs(grid$Precipitation - p) < 1e-12 &
        abs(grid$Clipping - c0) < 1e-12
    )
    
    iu <- which(
      abs(grid$Warming - 0) < 1e-12 &
        abs(grid$Precipitation - p) < 1e-12 &
        abs(grid$Clipping - c0) < 1e-12
    )
    
    if (length(iw) != 1 || length(iu) != 1) {
      stop("Could not identify a unique warming contrast in emmeans grid.")
    }
    
    w <- rep(0, nrow(grid))
    w[iw] <- 1
    w[iu] <- -1
    overall_weight <- overall_weight + w / nrow(combos)
    
    label <- paste0(
      precip_label(p),
      " | ",
      ifelse(c0 == 1, "Clipped", "Unclipped")
    )
    
    cc <- emmeans::contrast(
      emm,
      method = setNames(list(w), label),
      adjust = "none"
    )
    
    context_rows[[j]] <- cbind(
      data.frame(
        Context = label,
        Precipitation = p,
        Clipping = c0,
        stringsAsFactors = FALSE
      ),
      summarize_one_emm_contrast(cc)
    )
  }
  
  cc_overall <- emmeans::contrast(
    emm,
    method = list(Overall_Warming = overall_weight),
    adjust = "none"
  )
  
  list(
    overall = summarize_one_emm_contrast(cc_overall),
    context = do.call(rbind, context_rows)
  )
}


# Targeted removal and jackknife analyses receive the same primary treatment
# model as the manuscript, plus the block-fixed sensitivity used elsewhere.
fit_targeted_sensitivity_models <- function(beta_df) {
  
  d <- prepare_sensitivity_model_data(beta_df)
  
  if (
    nrow(d) < 30 ||
    any(!is.finite(d$Precipitation))
  ) {
    return(list(
      overall = data.frame(),
      context = data.frame(),
      errors = "Insufficient or invalid data."
    ))
  }
  
  model_specs <- list(
    Primary_standard = list(
      formula = Beta_sensitivity ~
        Warming * Precipitation * Clipping +
        (1 | Block/WholePlotID)
    ),
    Block_fixed_sensitivity = list(
      formula = Beta_sensitivity ~
        Warming * Precipitation * Clipping +
        Block +
        (1 | BlockWholePlotID)
    )
  )
  
  overall_rows <- list()
  context_rows <- list()
  error_rows <- character(0)
  
  for (model_name in names(model_specs)) {
    
    m <- tryCatch(
      lmerTest::lmer(
        model_specs[[model_name]]$formula,
        data = d,
        REML = TRUE,
        control = lme4::lmerControl(
          optimizer = "bobyqa",
          optCtrl = list(maxfun = 2e5)
        )
      ),
      error = function(e) e
    )
    
    if (inherits(m, "error")) {
      error_rows <- c(
        error_rows,
        paste0(model_name, ": ", conditionMessage(m))
      )
      next
    }
    
    ex <- tryCatch(
      extract_sensitivity_warming_contrasts(m),
      error = function(e) e
    )
    
    if (inherits(ex, "error")) {
      error_rows <- c(
        error_rows,
        paste0(
          model_name,
          " contrast extraction: ",
          conditionMessage(ex)
        )
      )
      next
    }
    
    singular <- lme4::isSingular(m, tol = 1e-6)
    
    overall_rows[[length(overall_rows) + 1]] <- cbind(
      data.frame(
        Model = model_name,
        Singular = singular,
        N = nrow(d),
        stringsAsFactors = FALSE
      ),
      ex$overall
    )
    
    cc <- ex$context
    cc$Model <- model_name
    cc$Singular <- singular
    cc$N <- nrow(d)
    context_rows[[length(context_rows) + 1]] <- cc
  }
  
  list(
    overall = if (length(overall_rows) > 0) {
      do.call(rbind, overall_rows)
    } else {
      data.frame()
    },
    context = if (length(context_rows) > 0) {
      do.call(rbind, context_rows)
    } else {
      data.frame()
    },
    errors = paste(error_rows, collapse = " | ")
  )
}


# Conservative block-matched overall warming effect. Within each block, first
# average the six precipitation x clipping warmed-minus-unwarmed contrasts, then
# use the four block means for a one-sample t test. This is used as the fast,
# design-aware summary for the random-subcomposition resampling distribution.
blockmatched_overall_warming <- function(beta_df) {
  
  d <- prepare_sensitivity_model_data(beta_df)
  
  unw <- d[d$Warming == 0, c(
    "Block", "Precipitation", "Clipping", "Beta_sensitivity"
  )]
  names(unw)[4] <- "Beta_unwarmed"
  
  war <- d[d$Warming == 1, c(
    "Block", "Precipitation", "Clipping", "Beta_sensitivity"
  )]
  names(war)[4] <- "Beta_warmed"
  
  pp <- merge(
    war,
    unw,
    by = c("Block", "Precipitation", "Clipping"),
    all = FALSE
  )
  
  pp$Difference <- pp$Beta_warmed - pp$Beta_unwarmed
  
  per_block <- aggregate(
    Difference ~ Block,
    data = pp,
    FUN = mean
  )
  
  x <- per_block$Difference[is.finite(per_block$Difference)]
  
  if (length(x) < 2 || stats::sd(x) == 0) {
    return(data.frame(
      N_pairs = nrow(pp),
      N_blocks = length(x),
      Estimate = ifelse(length(x) > 0, mean(x), NA_real_),
      SE = NA_real_,
      df = length(x) - 1,
      CI_low = NA_real_,
      CI_high = NA_real_,
      P = NA_real_,
      stringsAsFactors = FALSE
    ))
  }
  
  tt <- stats::t.test(x, mu = 0)
  
  data.frame(
    N_pairs = nrow(pp),
    N_blocks = length(x),
    Estimate = mean(x),
    SE = stats::sd(x) / sqrt(length(x)),
    df = unname(tt$parameter),
    CI_low = tt$conf.int[1],
    CI_high = tt$conf.int[2],
    P = tt$p.value,
    stringsAsFactors = FALSE
  )
}


# Add Holm correction within each grouping defined by key columns.
add_holm_by_keys <- function(d, key_cols, p_col = "P", out_col = "P_Holm") {
  
  if (nrow(d) == 0) {
    d[[out_col]] <- numeric(0)
    return(d)
  }
  
  key <- do.call(
    paste,
    c(d[key_cols], sep = "||")
  )
  
  out <- rep(NA_real_, nrow(d))
  
  for (k in unique(key)) {
    ii <- which(key == k)
    out[ii] <- stats::p.adjust(d[[p_col]][ii], method = "holm")
  }
  
  d[[out_col]] <- out
  d
}


taxon_cv_summary <- function(mean_abun, variance_abun) {
  
  keep <- is.finite(mean_abun) &
    is.finite(variance_abun) &
    mean_abun > 0 &
    variance_abun >= 0
  
  mu <- mean_abun[keep]
  vv <- variance_abun[keep]
  
  if (length(mu) == 0) {
    return(c(
      Median = NA_real_,
      Mean = NA_real_,
      Weighted = NA_real_
    ))
  }
  
  cv <- sqrt(vv) / mu
  
  w <- mu / sum(mu)
  
  c(
    Median = median(cv, na.rm = TRUE),
    Mean = mean(cv, na.rm = TRUE),
    Weighted = sum(w * cv, na.rm = TRUE)
  )
}


bray_curtis_two <- function(p, q) {
  den <- sum(p + q)
  if (!is.finite(den) || den <= 0) return(NA_real_)
  sum(abs(p - q)) / den
}


community_metrics <- function(mat, years,
                              run_aitchison = FALSE) {
  
  # Convert taxa x years -> years x taxa.
  comp <- t(mat)
  
  # Re-normalize defensively to exact compositions.
  rs <- rowSums(comp)
  if (any(rs <= 0)) {
    stop("At least one yearly sample has total abundance <= 0.")
  }
  comp <- sweep(comp, 1, rs, "/")
  
  n <- nrow(comp)
  
  zero_fraction_by_year <- rowMeans(comp == 0)
  mean_zero_fraction <- mean(zero_fraction_by_year)
  
  # ----------------------------------------------------------
  # Hellinger metrics: PRIMARY for sparse relative-abundance data.
  # ----------------------------------------------------------
  hel <- sqrt(comp)
  
  centroid <- colMeans(hel)
  d_to_centroid <- sqrt(
    rowSums(
      (hel - matrix(
        centroid,
        nrow = n,
        ncol = ncol(hel),
        byrow = TRUE
      ))^2
    )
  )
  
  # Root-mean-square distance from the temporal centroid.
  ctv_hellinger_rms <- sqrt(mean(d_to_centroid^2))
  
  # Mean pairwise distance over all pairs of years.
  pair_hellinger <- as.numeric(dist(hel, method = "euclidean"))
  mean_pairwise_hellinger <- mean(pair_hellinger)
  
  # ----------------------------------------------------------
  # Annual turnover: consecutive years.
  # ----------------------------------------------------------
  annual_hellinger <- rep(NA_real_, n - 1)
  annual_bray <- rep(NA_real_, n - 1)
  
  for (k in seq_len(n - 1)) {
    annual_hellinger[k] <- sqrt(
      sum((hel[k + 1, ] - hel[k, ])^2)
    )
    
    annual_bray[k] <- bray_curtis_two(
      comp[k, ],
      comp[k + 1, ]
    )
  }
  
  # ----------------------------------------------------------
  # Mean pairwise Bray-Curtis across all year pairs.
  # ----------------------------------------------------------
  pair_bray <- c()
  
  if (n >= 2) {
    for (i in 1:(n - 1)) {
      for (j in (i + 1):n) {
        pair_bray <- c(
          pair_bray,
          bray_curtis_two(comp[i, ], comp[j, ])
        )
      }
    }
  }
  
  mean_pairwise_bray <- mean(pair_bray, na.rm = TRUE)
  
  # ----------------------------------------------------------
  # OPTIONAL Aitchison/CLR sensitivity analysis.
  # Important: high zero fractions can make CLR results sensitive
  # to the zero-replacement method.
  # ----------------------------------------------------------
  aitchison_ctv_rms <- NA_real_
  mean_pairwise_aitchison <- NA_real_
  annual_aitchison <- rep(NA_real_, n - 1)
  
  if (run_aitchison &&
      requireNamespace("zCompositions", quietly = TRUE)) {
    
    # Remove taxa absent in all years, if any remain.
    keep_taxa <- colSums(comp) > 0
    comp_a <- comp[, keep_taxa, drop = FALSE]
    
    repl <- tryCatch(
      zCompositions::cmultRepl(
        comp_a,
        label = 0,
        method = "CZM",
        output = "prop"
      ),
      error = function(e) {
        warning("Aitchison zero replacement failed: ", e$message)
        NULL
      }
    )
    
    if (!is.null(repl)) {
      clr <- log(repl) - rowMeans(log(repl))
      
      clr_centroid <- colMeans(clr)
      
      d_clr_centroid <- sqrt(
        rowSums(
          (clr - matrix(
            clr_centroid,
            nrow = nrow(clr),
            ncol = ncol(clr),
            byrow = TRUE
          ))^2
        )
      )
      
      aitchison_ctv_rms <- sqrt(
        mean(d_clr_centroid^2)
      )
      
      mean_pairwise_aitchison <- mean(
        as.numeric(dist(clr, method = "euclidean"))
      )
      
      for (k in seq_len(n - 1)) {
        annual_aitchison[k] <- sqrt(
          sum((clr[k + 1, ] - clr[k, ])^2)
        )
      }
    }
  }
  
  annual_table <- data.frame(
    Year_from = years[-length(years)],
    Year_to = years[-1],
    Hellinger_turnover = annual_hellinger,
    BrayCurtis_turnover = annual_bray,
    Aitchison_turnover = annual_aitchison,
    stringsAsFactors = FALSE
  )
  
  list(
    CTV_Hellinger_RMS = ctv_hellinger_rms,
    MeanPairwise_Hellinger = mean_pairwise_hellinger,
    MeanAnnual_Hellinger = mean(annual_hellinger, na.rm = TRUE),
    
    MeanPairwise_BrayCurtis = mean_pairwise_bray,
    MeanAnnual_BrayCurtis = mean(annual_bray, na.rm = TRUE),
    
    CTV_Aitchison_RMS = aitchison_ctv_rms,
    MeanPairwise_Aitchison = mean_pairwise_aitchison,
    MeanAnnual_Aitchison = if (all(is.na(annual_aitchison))) {
      NA_real_
    } else {
      mean(annual_aitchison, na.rm = TRUE)
    },
    
    MeanZeroFraction = mean_zero_fraction,
    annual_table = annual_table
  )
}


