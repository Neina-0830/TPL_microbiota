# Vectorized linear detrending across all taxa.
# Input: taxa x years matrix.
# Output: temporal variance of linear-detrended residuals for every taxon.
detrended_variance <- function(mat, years) {
  
  years <- as.numeric(years)
  
  if (length(unique(years)) < 3) {
    stop("At least 3 distinct years are needed for linear detrending.")
  }
  
  # Center year to improve numerical stability.
  yr <- years - mean(years)
  
  X <- cbind(Intercept = 1, Year = yr)
  
  # coefficients: 2 x taxa
  coef_mat <- solve(crossprod(X), crossprod(X, t(mat)))
  
  # fitted: taxa x years
  fitted_mat <- t(X %*% coef_mat)
  
  residual_mat <- mat - fitted_mat
  
  # This is var(residuals) using the same n-1 denominator as base R::var().
  # Since residual mean is essentially zero:
  v_resid <- rowSums(residual_mat^2) / (ncol(mat) - 1)
  
  # Numerical protection.
  v_resid[v_resid < 0 & abs(v_resid) < 1e-15] <- 0
  
  v_resid
}


fit_taylor <- function(mean_abun, variance_abun, x_ref_log10) {
  
  keep <- is.finite(mean_abun) &
    is.finite(variance_abun) &
    mean_abun > 0 &
    variance_abun > 0
  
  if (sum(keep) < 3) {
    return(list(
      Intercept = NA_real_,
      Beta = NA_real_,
      SE_Intercept = NA_real_,
      SE_Beta = NA_real_,
      Cov_Intercept_Beta = NA_real_,
      Cor_Intercept_Beta = NA_real_,
      R2 = NA_real_,
      P_Beta = NA_real_,
      LogVar_at_ref = NA_real_,
      SE_LogVar_at_ref = NA_real_,
      Cov_LogVarRef_Beta = NA_real_,
      Cor_LogVarRef_Beta = NA_real_,
      n_taxa = sum(keep),
      table = data.frame()
    ))
  }
  
  d <- data.frame(
    Mean = mean_abun[keep],
    Variance = variance_abun[keep]
  )
  
  d$LogMean <- log10(d$Mean)
  d$LogVar <- log10(d$Variance)
  
  # Original parameterization used in the manuscript.
  fit_raw <- lm(LogVar ~ LogMean, data = d)
  s_raw <- summary(fit_raw)
  vc_raw <- vcov(fit_raw)
  
  # Center LogMean at a COMMON abundance reference within each microbial group.
  # This gives an interpretable "log variance at reference abundance" and
  # reduces the purely geometric intercept-slope correlation.
  d$LogMean_centered <- d$LogMean - x_ref_log10
  fit_ref <- lm(LogVar ~ LogMean_centered, data = d)
  s_ref <- summary(fit_ref)
  vc_ref <- vcov(fit_ref)
  
  cor_raw <- vc_raw[1, 2] /
    sqrt(vc_raw[1, 1] * vc_raw[2, 2])
  
  cor_ref <- vc_ref[1, 2] /
    sqrt(vc_ref[1, 1] * vc_ref[2, 2])
  
  list(
    Intercept = unname(coef(fit_raw)[1]),
    Beta = unname(coef(fit_raw)[2]),
    SE_Intercept = unname(s_raw$coefficients[1, 2]),
    SE_Beta = unname(s_raw$coefficients[2, 2]),
    Cov_Intercept_Beta = unname(vc_raw[1, 2]),
    Cor_Intercept_Beta = unname(cor_raw),
    R2 = unname(s_raw$r.squared),
    P_Beta = unname(s_raw$coefficients[2, 4]),
    
    LogVar_at_ref = unname(coef(fit_ref)[1]),
    SE_LogVar_at_ref = unname(s_ref$coefficients[1, 2]),
    Cov_LogVarRef_Beta = unname(vc_ref[1, 2]),
    Cor_LogVarRef_Beta = unname(cor_ref),
    
    n_taxa = nrow(d),
    table = d
  )
}


