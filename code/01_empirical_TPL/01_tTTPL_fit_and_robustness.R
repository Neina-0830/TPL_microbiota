# -----------------------------
# 5. COMMON ABUNDANCE REFERENCE FOR EACH GROUP
# -----------------------------
#
# The ordinary TPL intercept is the predicted log variance when
# log10(mean abundance)=0, i.e. mean abundance=1. For relative-abundance
# data this is generally not a biologically representative abundance.
#
# Therefore, for each microbial group, we calculate one common reference:
# x_ref = median pooled log10(mean abundance)
#
# We then save LogVar_at_ref for every plot.
# -------------------------------------------------------------

get_group_xref <- function(group, env) {
  
  folder <- file.path(INPUT_ROOT, group)
  
  # Build the 48 expected plot files explicitly from metadata.
  # This intentionally ignores any extra aggregate/intermediate files
  # that may coexist in the same directory.
  expected_files <- file.path(
    folder,
    paste0(PLOT_LIST, "_UPARSE_otu_All_abun.csv")
  )
  
  exists_flag <- file.exists(expected_files)
  
  if (!any(exists_flag)) {
    stop("No expected plot-level UPARSE files found for group: ", group)
  }
  
  if (any(!exists_flag)) {
    warning(
      group, ": missing ", sum(!exists_flag),
      " expected plot-level file(s): ",
      paste(PLOT_LIST[!exists_flag], collapse = ", ")
    )
  }
  
  plot_ids <- PLOT_LIST[exists_flag]
  files <- expected_files[exists_flag]
  
  values <- vector("list", length(files))
  
  for (i in seq_along(files)) {
    
    plot_id <- plot_ids[i]
    
    mat <- read_otu_matrix(files[i])
    ali <- align_plot_to_metadata(mat, plot_id, env)
    mat <- ali$mat
    
    mu <- rowMeans(mat)
    values[[i]] <- log10(mu[is.finite(mu) & mu > 0])
  }
  
  pooled <- unlist(values, use.names = FALSE)
  
  if (length(pooled) == 0) {
    stop("No positive taxon means found for group: ", group)
  }
  
  median(pooled)
}


