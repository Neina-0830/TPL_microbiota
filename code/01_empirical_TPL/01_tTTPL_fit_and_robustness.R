# Fast analytical TPL fit used only for repeated sensitivity calculations.
# It is algebraically identical to lm(log10(Variance) ~ log10(Mean)) for the
# slope, standard error and R2, but avoids constructing tens of thousands of lm
# objects during random-subcomposition resampling.
fit_taylor_fast_beta <- function(mean_abun, variance_abun) {
  
  keep <- is.finite(mean_abun) &
    is.finite(variance_abun) &
    mean_abun > 0 &
    variance_abun > 0
  
  n <- sum(keep)
  
  if (n < 3) {
    return(list(
      Beta = NA_real_,
      SE_Beta = NA_real_,
      R2 = NA_real_,
      P_Beta = NA_real_,
      n_taxa = n
    ))
  }
  
  x <- log10(mean_abun[keep])
  y <- log10(variance_abun[keep])
  
  xbar <- mean(x)
  ybar <- mean(y)
  xc <- x - xbar
  yc <- y - ybar
  
  sxx <- sum(xc^2)
  syy <- sum(yc^2)
  sxy <- sum(xc * yc)
  
  if (!is.finite(sxx) || sxx <= 0) {
    return(list(
      Beta = NA_real_,
      SE_Beta = NA_real_,
      R2 = NA_real_,
      P_Beta = NA_real_,
      n_taxa = n
    ))
  }
  
  beta <- sxy / sxx
  intercept <- ybar - beta * xbar
  resid <- y - (intercept + beta * x)
  sse <- sum(resid^2)
  
  se_beta <- if (n > 2) {
    sqrt((sse / (n - 2)) / sxx)
  } else {
    NA_real_
  }
  
  r2 <- if (is.finite(syy) && syy > 0) {
    1 - sse / syy
  } else {
    NA_real_
  }
  
  p_beta <- if (
    is.finite(se_beta) &&
    se_beta > 0 &&
    n > 2
  ) {
    2 * stats::pt(
      abs(beta / se_beta),
      df = n - 2,
      lower.tail = FALSE
    )
  } else {
    NA_real_
  }
  
  list(
    Beta = beta,
    SE_Beta = se_beta,
    R2 = r2,
    P_Beta = p_beta,
    n_taxa = n
  )
}


# Remove a fixed set of taxa and re-close every annual sample to sum to one.
# Returning NULL indicates that removal created an invalid subcomposition.
remove_taxa_and_renormalize <- function(mat, remove_taxa = character(0)) {
  
  remove_taxa <- unique(as.character(remove_taxa))
  keep <- !(rownames(mat) %in% remove_taxa)
  
  if (sum(keep) < 3) return(NULL)
  
  z <- mat[keep, , drop = FALSE]
  totals <- colSums(z)
  
  if (
    any(!is.finite(totals)) ||
    any(totals <= 0)
  ) {
    return(NULL)
  }
  
  z <- sweep(z, 2, totals, "/")
  
  if (any(!is.finite(z))) return(NULL)
  
  z
}


# Load and align all canonical plot-level matrices for one microbial group once.
# The cache prevents repeated disk reads during the resampling analyses.
load_group_plot_cache <- function(group, env) {
  
  folder <- file.path(INPUT_ROOT, group)
  expected_files <- file.path(
    folder,
    paste0(PLOT_LIST, "_UPARSE_otu_All_abun.csv")
  )
  
  exists_flag <- file.exists(expected_files)
  
  if (!any(exists_flag)) {
    stop("No expected plot-level files found for group: ", group)
  }
  
  plot_ids <- PLOT_LIST[exists_flag]
  files <- expected_files[exists_flag]
  cache <- vector("list", length(files))
  
  for (i in seq_along(files)) {
    mat <- read_otu_matrix(files[i])
    ali <- align_plot_to_metadata(mat, plot_ids[i], env)
    
    cache[[i]] <- list(
      plot_id = plot_ids[i],
      mat = ali$mat,
      meta = ali$meta,
      md = plot_metadata_one_row(ali$meta)
    )
  }
  
  names(cache) <- plot_ids
  cache
}


# Build two GLOBAL taxon rankings within each microbial group.
# 1) abundance ranking: mean relative abundance pooled across all annual samples.
# 2) temporal-trend ranking: mean absolute linear slope across all plot
#    trajectories. Taxa absent from a plot contribute a slope of zero in that
#    plot, which avoids preferentially ranking rare taxa observed only locally.
build_group_taxon_rankings <- function(cache) {
  
  all_taxa <- sort(unique(unlist(
    lapply(cache, function(z) rownames(z$mat)),
    use.names = FALSE
  )))
  
  if (length(all_taxa) < 4) {
    stop("Fewer than four taxa are available for sensitivity analysis.")
  }
  
  abundance_sum <- setNames(
    numeric(length(all_taxa)),
    all_taxa
  )
  
  abs_slope_sum <- setNames(
    numeric(length(all_taxa)),
    all_taxa
  )
  
  signed_slope_sum <- setNames(
    numeric(length(all_taxa)),
    all_taxa
  )
  
  total_samples <- 0
  n_plots <- length(cache)
  
  for (z in cache) {
    
    mat <- z$mat
    taxa <- rownames(mat)
    total_samples <- total_samples + ncol(mat)
    
    rs <- rowSums(mat)
    abundance_sum[taxa] <- abundance_sum[taxa] + rs
    
    yr <- as.numeric(z$meta$year)
    yrc <- yr - mean(yr)
    denom <- sum(yrc^2)
    
    if (!is.finite(denom) || denom <= 0) {
      stop("Invalid year variance while ranking temporal trends.")
    }
    
    # With centered year, slope = sum(y_t * centered_year_t) / sum(centered_year^2).
    slopes <- as.numeric(mat %*% yrc) / denom
    names(slopes) <- taxa
    
    abs_slope_sum[taxa] <- abs_slope_sum[taxa] + abs(slopes)
    signed_slope_sum[taxa] <- signed_slope_sum[taxa] + slopes
  }
  
  pooled_mean <- abundance_sum / total_samples
  abundance_share <- pooled_mean / sum(pooled_mean)
  
  abundance <- data.frame(
    Taxon = all_taxa,
    PooledMeanRelativeAbundance = as.numeric(pooled_mean[all_taxa]),
    AbundanceShare = as.numeric(abundance_share[all_taxa]),
    stringsAsFactors = FALSE
  )
  
  abundance <- abundance[
    order(
      abundance$PooledMeanRelativeAbundance,
      decreasing = TRUE
    ),
    ,
    drop = FALSE
  ]
  abundance$AbundanceRank <- seq_len(nrow(abundance))
  abundance$CumulativeAbundanceShare <- cumsum(abundance$AbundanceShare)
  
  trend <- data.frame(
    Taxon = all_taxa,
    MeanAbsoluteLinearTrend = as.numeric(abs_slope_sum[all_taxa]) / n_plots,
    MeanSignedLinearTrend = as.numeric(signed_slope_sum[all_taxa]) / n_plots,
    stringsAsFactors = FALSE
  )
  
  trend <- trend[
    order(
      trend$MeanAbsoluteLinearTrend,
      decreasing = TRUE
    ),
    ,
    drop = FALSE
  ]
  trend$TrendRank <- seq_len(nrow(trend))
  
  combined <- merge(
    abundance,
    trend,
    by = "Taxon",
    all = TRUE,
    sort = FALSE
  )
  
  combined <- combined[
    order(combined$AbundanceRank),
    ,
    drop = FALSE
  ]
  
  list(
    abundance = abundance,
    trend = trend,
    combined = combined,
    total_samples = total_samples,
    n_plots = n_plots
  )
}


# -----------------------------------------------------------------------------
# TEMPORAL-TREND CONCENTRATION
# -----------------------------------------------------------------------------
# Reviewer question addressed directly:
#   "Are a small number of taxa driving temporal trends?"
#
# For each plot, fit a linear abundance ~ year slope for every taxon. Because
# positive and negative slopes would cancel under the compositional constraint,
# concentration is defined from ABSOLUTE slopes. If a small number of taxa carry
# most of the total absolute slope magnitude, temporal change is concentrated;
# if the share is diffuse, many taxa contribute.
#
# This is deliberately descriptive. The targeted-removal analysis below asks the
# separate robustness question: even if the strongest-trending taxa are removed,
# does the warming effect on beta persist?
# -----------------------------------------------------------------------------

trend_concentration_metrics <- function(scores, top_k, fractions) {
  
  scores <- as.numeric(scores)
  scores <- scores[is.finite(scores) & scores >= 0]
  
  n_taxa <- length(scores)
  total <- sum(scores)
  
  if (n_taxa == 0 || !is.finite(total) || total <= 0) {
    out <- list(
      N_taxa = n_taxa,
      N_nonzero_trend_taxa = sum(scores > 0),
      Total_absolute_trend = total,
      Trend_HHI = NA_real_,
      Effective_number_trend_taxa = NA_real_,
      N_taxa_for_50pct_trend = NA_integer_,
      Fraction_taxa_for_50pct_trend = NA_real_,
      N_taxa_for_80pct_trend = NA_integer_,
      Fraction_taxa_for_80pct_trend = NA_real_
    )
    
    for (k in top_k) {
      out[[paste0("Top", k, "_taxa_trend_share")]] <- NA_real_
    }
    for (frac in fractions) {
      lab <- paste0(round(frac * 100), "pct")
      out[[paste0("Top", lab, "_taxa_trend_share")]] <- NA_real_
      out[[paste0("Top", lab, "_N_taxa")]] <- NA_integer_
    }
    
    return(out)
  }
  
  ord <- sort(scores, decreasing = TRUE)
  shares <- ord / total
  cshare <- cumsum(shares)
  
  hhi <- sum(shares^2)
  eff_n <- if (is.finite(hhi) && hhi > 0) 1 / hhi else NA_real_
  
  n50 <- which(cshare >= 0.50)[1]
  n80 <- which(cshare >= 0.80)[1]
  
  out <- list(
    N_taxa = n_taxa,
    N_nonzero_trend_taxa = sum(ord > 0),
    Total_absolute_trend = total,
    Trend_HHI = hhi,
    Effective_number_trend_taxa = eff_n,
    N_taxa_for_50pct_trend = as.integer(n50),
    Fraction_taxa_for_50pct_trend = n50 / n_taxa,
    N_taxa_for_80pct_trend = as.integer(n80),
    Fraction_taxa_for_80pct_trend = n80 / n_taxa
  )
  
  for (k in top_k) {
    kk <- min(as.integer(k), n_taxa)
    out[[paste0("Top", k, "_taxa_trend_share")]] <- sum(shares[seq_len(kk)])
  }
  
  for (frac in fractions) {
    nn <- max(1L, ceiling(n_taxa * frac))
    nn <- min(nn, n_taxa)
    lab <- paste0(round(frac * 100), "pct")
    out[[paste0("Top", lab, "_taxa_trend_share")]] <- sum(shares[seq_len(nn)])
    out[[paste0("Top", lab, "_N_taxa")]] <- nn
  }
  
  out
}


