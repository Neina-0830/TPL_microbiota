# instead test whether the warming effect on beta is robust to:
#
# A) direct temporal-trend concentration: quantify whether the strongest-trending
#    few taxa account for a disproportionate share of total absolute temporal trend;
# B) targeted removal of abundance-dominant taxa AND strongest-trend taxa;
# C) leave-one-driver-out jackknife among the top 10 taxa in each ranking;
# D) repeated random subcomposition at 1%, 5% and 10% taxon removal.
#
# IMPORTANT: annual sampling resolves interannual, not seasonal, variability.
