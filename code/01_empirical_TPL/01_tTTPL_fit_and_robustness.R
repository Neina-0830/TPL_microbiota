# -----------------------------
# 10. SLOPE-INTERCEPT CO-VARIATION
# -----------------------------
#
# Two versions are saved:
# A) ordinary Intercept_raw vs Beta_raw
# B) LogVar_at_ref_raw vs Beta_raw
#
# Version B is more interpretable because the reference abundance lies
# inside the observed abundance distribution.
# -------------------------------------------------------------

slope_intercept_results <- list()
si_counter <- 1

for (group in unique(all_metrics$Group)) {
  
  d <- all_metrics[all_metrics$Group == group, , drop = FALSE]
  
  for (warm_level in c(0, 1)) {
    
    z <- d[d$warm == warm_level, , drop = FALSE]
    
    ok1 <- is.finite(z$Intercept_raw) &
      is.finite(z$Beta_raw)
    
    ok2 <- is.finite(z$LogVar_at_ref_raw) &
      is.finite(z$Beta_raw)
    
    cor_raw <- if (sum(ok1) >= 3) {
      cor.test(
        z$Intercept_raw[ok1],
        z$Beta_raw[ok1],
        method = "pearson"
      )
    } else NULL
    
    cor_ref <- if (sum(ok2) >= 3) {
      cor.test(
        z$LogVar_at_ref_raw[ok2],
        z$Beta_raw[ok2],
        method = "pearson"
      )
    } else NULL
    
    slope_intercept_results[[si_counter]] <- data.frame(
      Group = group,
      warm = warm_level,
      n_raw = sum(ok1),
      Pearson_r_Intercept_Beta =
        if (is.null(cor_raw)) NA_real_ else unname(cor_raw$estimate),
      P_Intercept_Beta =
        if (is.null(cor_raw)) NA_real_ else cor_raw$p.value,
      
      n_ref = sum(ok2),
      Pearson_r_LogVarRef_Beta =
        if (is.null(cor_ref)) NA_real_ else unname(cor_ref$estimate),
      P_LogVarRef_Beta =
        if (is.null(cor_ref)) NA_real_ else cor_ref$p.value,
      
      stringsAsFactors = FALSE
    )
    
    si_counter <- si_counter + 1
  }
}

slope_intercept_results <- do.call(
