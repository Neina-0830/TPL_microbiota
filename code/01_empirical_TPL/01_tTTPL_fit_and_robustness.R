# -----------------------------
# 12. OPTIONAL:
#     PREDICTED VARIANCE CURVE INPUT TABLE
# -----------------------------
#
# This table is designed for later plotting:
#
# log10(Var) = LogVar_at_ref + Beta *
#              (log10(Mean) - Log10MeanReference)
#
# It creates a common abundance grid for each plot.
# You can later average model predictions by treatment or use emmeans.
# -------------------------------------------------------------

variance_curve_list <- list()
vc_counter <- 1

N_GRID <- 100

for (group in unique(all_metrics$Group)) {
  
  # Estimate group-wide observed range from saved taxon tables if available.
  # If taxon tables are not saved, use a conservative reference-centered range.
  group_taxon_dir <- file.path(
    OUTPUT_ROOT, group, "taxon_tables"
  )
  
  tax_files <- list.files(
    group_taxon_dir,
    pattern = "_UPARSE_taxon_temporal_metrics\\.csv$",
    full.names = TRUE
  )
  
  if (length(tax_files) > 0) {
    
    logmean_pool <- unlist(
      lapply(
        tax_files,
        function(f) {
          z <- read.csv(f, stringsAsFactors = FALSE)
          z$LogMean[is.finite(z$LogMean)]
        }
      ),
      use.names = FALSE
    )
    
    x_min <- as.numeric(
      quantile(logmean_pool, 0.01, na.rm = TRUE)
    )
    x_max <- as.numeric(
      quantile(logmean_pool, 0.99, na.rm = TRUE)
    )
    
  } else {
    
    xr <- unique(
      all_metrics$Log10MeanReference[
        all_metrics$Group == group
      ]
    )[1]
    
    x_min <- xr - 2
    x_max <- xr + 2
  }
  
  x_grid <- seq(x_min, x_max, length.out = N_GRID)
  
  d <- all_metrics[
    all_metrics$Group == group,
    ,
    drop = FALSE
  ]
  
  for (i in seq_len(nrow(d))) {
    
    pred_logvar <- d$LogVar_at_ref_raw[i] +
      d$Beta_raw[i] *
      (x_grid - d$Log10MeanReference[i])
    
    variance_curve_list[[vc_counter]] <- data.frame(
      Group = group,
      Plot = d$Plot[i],
      block = d$block[i],
      Number = d$Number[i],
      warm = d$warm[i],
      precip = d$precip[i],
      clip = d$clip[i],
      Treatment = d$Treatment[i],
      LogMean = x_grid,
      MeanAbundance = 10^x_grid,
      PredictedLogVar = pred_logvar,
      PredictedVariance = 10^pred_logvar,
      stringsAsFactors = FALSE
    )
    
    vc_counter <- vc_counter + 1
  }
}

variance_curve <- do.call(
